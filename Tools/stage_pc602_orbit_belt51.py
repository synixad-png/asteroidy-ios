#!/usr/bin/env python3
"""Bake ONLY the PC602 820-rock orbital belt from source, not the full PC ZIP.

Reads the byte-verified H290 collision map already generated by
Tools/stage_pc602_newhome290.py. Compiles the original C#-math port
Tools/PC602OrbitBelt51.cs using .NET 8 (deterministic seeded System.Random),
then validates the 820 individually subdivided original asteroid meshes.
The resulting resource is staged at build time; it is not committed as
a duplicate asset archive, and the source C# is the single generator.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import tempfile

COUNT=820
HEADER=16
ENTRY=28
STRIDE=40

def sha(data:bytes)->str:
    return hashlib.sha256(data).hexdigest()

def verify(path:Path):
    with path.open("rb") as handle:
        header=handle.read(HEADER)
        if len(header)!=HEADER or header[:4]!=b"B051":
            raise ValueError("Original PC602 belt header B051 missing")
        version,number,vertices=struct.unpack_from("<III",header,4)
        if version!=1 or number!=COUNT or vertices<=0 or vertices%3:
            raise ValueError("Original belt version/count/vertex count invalid")
        if path.stat().st_size != HEADER+COUNT*ENTRY+vertices*STRIDE:
            raise ValueError("Original PC602 vertex buffer incomplete")
        offset=0
        sizes={"basic":0,"detailed":0}
        for i in range(COUNT):
            raw=handle.read(ENTRY)
            if len(raw)!=ENTRY:raise ValueError("Truncated PC602 stone table")
            x,y,z,size,seed,first,count=struct.unpack("<5fII",raw)
            source_count=3840 if size>1.15 else 960
            if not all(map(lambda n:n==n and abs(n)<1e9,[x,y,z,size,seed])):
                raise ValueError(f"Nonfinite source asteroid {i}")
            if first!=offset or count!=source_count or abs(seed-i*0.73)>0.001:
                raise ValueError(f"Wrong original asteroid mesh interval at {i}")
            sizes["detailed" if count==3840 else "basic"]+=1
            offset+=count
        if offset!=vertices:
            raise ValueError("Source Belt51 mesh vertex count mismatch")
        if handle.tell()!=HEADER+COUNT*ENTRY:
            raise ValueError("Incorrect source mesh data start")
    return {"result":"PASS","source":"Windows/src/OrbitWorld51.cs + GpuIntro41.cs",
            "objects":COUNT,"vertices":vertices,"triangles":vertices//3,
            "basic":sizes["basic"],"detailed":sizes["detailed"],
            "bytes":path.stat().st_size,"sha256":sha(path.read_bytes())}

def build(root:Path,destination:Path):
    source=root/"Tools/PC602OrbitBelt51.cs"
    height=destination/"PC602Home290HeightMap.bin"
    if not source.is_file() or not height.is_file():
        raise FileNotFoundError("Missing exact-source PC602 C# or H290 height map")
    expected="12d56a99634e4fc28ded9e03bcac34de05020750cc18e86d1086db8542b2d18d"
    if sha(height.read_bytes())!=expected:
        raise ValueError("Refuse asteroid bake on non-original H290 surface")
    dest=destination/"PC602OrbitBelt51.bin"
    # Do not regenerate or overwrite already verified resources.
    if dest.exists():return verify(dest)
    with tempfile.TemporaryDirectory(prefix="pc602_belt_") as work:
        project=Path(work)
        (project/"PC602OrbitBelt51.csproj").write_text(
            '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup>'
            '<OutputType>Exe</OutputType><TargetFramework>net8.0</TargetFramework>'
            '<Nullable>enable</Nullable><ImplicitUsings>enable</ImplicitUsings>'
            '</PropertyGroup></Project>\n')
        (project/"Program.cs").write_bytes(source.read_bytes())
        candidate=project/"belt.bin"
        cmd=["dotnet","run","--project",str(project/"PC602OrbitBelt51.csproj"),
             "--configuration","Release","--",str(height.resolve()),str(candidate)]
        subprocess.run(cmd,check=True,timeout=800)
        proof=verify(candidate)
        # Atomic stage — do not leave a partially written binary in the app.
        candidate.replace(dest)
        return proof

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root",type=Path,default=Path(__file__).resolve().parents[1])
    p.add_argument("--destination",type=Path)
    args=p.parse_args()
    destination=args.destination or args.root/"ASTEROIDYiOS/Assets"
    try:
        print(json.dumps(build(args.root,destination),sort_keys=True))
    except (OSError,ValueError,subprocess.CalledProcessError,
            subprocess.TimeoutExpired) as exc:
        print("FAIL PC602 original belt: "+str(exc),file=sys.stderr)
        return 1
    return 0

if __name__=="__main__":
    raise SystemExit(main())
